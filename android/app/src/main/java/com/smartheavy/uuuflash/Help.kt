package com.smartheavy.uuuflash

import android.graphics.Typeface
import android.text.SpannableStringBuilder
import android.text.style.StyleSpan

/** Инструкция за иконкой ⓘ в шапке. Текст согласован 23.11.2026. */
object Help {

    const val TITLE = "Как прошить панель"

    fun text(): CharSequence = SpannableStringBuilder().apply {
        step("1. Подключение.", "Подключите панель к телефону через OTG-переходник USB-C → USB-A.")
        step(
            "2. Режим прошивки.",
            "Выключите питание панели, зажмите скрытую кнопку и включите питание. " +
                "В приложении появится «Панель подключена». Если телефон спросит «Открыть UUU Flash?», отметьте «Всегда».",
        )
        step(
            "3. Файлы.",
            "Сохраните файлы из Telegram на телефон. Загрузчик — imx-boot-pm-<машина>…, прошивка — …wic.zst той же машины.",
        )
        step(
            "4. Память.",
            "Если знаете объём, выберите 4 ГБ или 2 ГБ. Если не знаете:\n" +
                "• Откройте «Проверка без записи» и нажмите «4 ГБ → RAM».\n" +
                "• «Успешно» — у панели 4 ГБ, можно сразу шить.\n" +
                "• Ошибка — снова включите режим прошивки (шаг 2) и нажмите «2 ГБ → RAM». «Успешно» — у панели 2 ГБ.\n" +
                "Объём запомнится и в следующий раз выберется сам (✓).",
        )
        step(
            "5. Прошивка.",
            "Нажмите «Прошить панель» и подтвердите. Это занимает 5–20 минут. " +
                "Приложение можно свернуть, ход прошивки виден в уведомлении.",
        )
        step(
            "6. После.",
            "Если включено «Перезагрузить после прошивки», панель загрузится сама. " +
                "Если нет, выключите и включите питание без кнопки.",
        )
        step(
            "Если что-то пошло не так:",
            "откройте «Лог», нажмите «Поделиться» и отправьте лог разработчику.",
            last = true,
        )
    }

    private fun SpannableStringBuilder.step(head: String, body: String, last: Boolean = false) {
        val start = length
        append(head)
        setSpan(StyleSpan(Typeface.BOLD), start, length, 0)
        append(" ").append(body)
        if (!last) append("\n\n")
    }
}
